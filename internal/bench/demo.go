// DemoNotice opens the demo document. It says what the document was made from
// and which of its parts are real.
const DemoNotice = "Generated by `make demo` from `deploy/configs/policy-fake.yaml`. " +
	"The providers are fake, so the served text is synthetic and the costs are what the fake usage is priced at. " +
	"The routing decisions are the real policy's."

// DemoProfiles are the profiles every prompt is explained under, in the order
// of the decision table.
var DemoProfiles = []string{"strict", "balanced", "economy"}

// demoServedProfile is the profile of the chat requests, one for each prompt.
const demoServedProfile = "balanced"

// DemoPrompt is a prompt of examples/prompts.json. The demo document names it
// and never repeats its text.
type DemoPrompt struct {
	Name   string `json:"name"`
	Prompt string `json:"prompt"`
}

// LoadDemoPrompts reads the prompts file at path: a list of {name, prompt}
// objects with unique names. An error names the file and never quotes a prompt.
func LoadDemoPrompts(path string) ([]DemoPrompt, error) {
	name := filepath.Base(path)
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read demo prompts: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var prompts []DemoPrompt
	if err := dec.Decode(&prompts); err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return nil, fmt.Errorf("%s: trailing data after the list of prompts", name)
	}
	if len(prompts) == 0 {
		return nil, fmt.Errorf("%s: no prompts", name)
	}
	seen := map[string]bool{}
	for i, p := range prompts {
		switch {
		case p.Name == "":
			return nil, fmt.Errorf("%s: prompt %d has no name", name, i+1)
		case p.Prompt == "":
			return nil, fmt.Errorf("%s: prompt %q has no prompt text", name, p.Name)
		case seen[p.Name]:
			return nil, fmt.Errorf("%s: duplicate prompt name %q", name, p.Name)
		}
		seen[p.Name] = true
	}
	return prompts, nil
}

// LoadDemoEvaluation reads evaluation.json from the trainer's reports
// directory. A file that does not exist is an error naming it.
func LoadDemoEvaluation(reportsDir string) (*Evaluation, error) {
	ev, err := loadTrainerFile[Evaluation](reportsDir, evaluationFileName, func(e *Evaluation) int { return e.SchemaVersion })
	if err != nil {
		return nil, err
	}
	if err := (ReportInputs{Evaluation: ev}).require(inEvaluation); err != nil {
		return nil, err
	}
	return ev, nil
}

// ExplainedCandidate is the part of a candidate of an explained decision that
// the demo reads. A figure the gateway leaves null is nil.
type ExplainedCandidate struct {
	Model           string   `json:"model"`
	P               *float64 `json:"p"`
	LCB             *float64 `json:"lcb"`
	BlockN          *int     `json:"block_n"`
	BlockK          *int     `json:"block_k"`
	ExpectedCostUSD *float64 `json:"expected_cost_usd"`
}

// ExplainedDecision is the part of the answer of POST /v1/routing/explain that
// the demo reads.
type ExplainedDecision struct {
	PolicyVersion string               `json:"policy_version"`
	Profile       string               `json:"profile"`
	Chosen        string               `json:"chosen"`
	Reason        string               `json:"reason"`
	Lambda        *float64             `json:"lambda"`
	Candidates    []ExplainedCandidate `json:"candidates"`
}

// Explain asks the gateway how it would route a chat request with a single
// user message, plus the given headers, without calling a provider. Any status
// but 200 is an error: unlike a chat request, an explanation has no outcome to
// report. The error never quotes the prompt.
func (c *Client) Explain(ctx context.Context, prompt string, headers map[string]string) (ExplainedDecision, error) {
	body, err := json.Marshal(chatBody{
		Model:    config.AutoModel,
		Messages: []chatMessage{{Role: "user", Content: prompt}},
	})
	if err != nil {
		return ExplainedDecision{}, fmt.Errorf("encode explain request: %w", err)
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, c.baseURL+"/v1/routing/explain", bytes.NewReader(body))
	if err != nil {
		return ExplainedDecision{}, fmt.Errorf("build explain request: %w", err)
	}
	req.Header.Set("Authorization", "Bearer "+c.key)
	req.Header.Set("Content-Type", "application/json")
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	resp, err := c.http.Do(req)
	if err != nil {
		return ExplainedDecision{}, fmt.Errorf("send explain request: %w", err)
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxResponseBytes))
	if err != nil {
		return ExplainedDecision{}, fmt.Errorf("read explain response: %w", err)
	}
	if resp.StatusCode != http.StatusOK {
		return ExplainedDecision{}, fmt.Errorf("explain: status %d (%s)", resp.StatusCode, errorCode(resp.StatusCode, data))
	}
	var d ExplainedDecision
	if err := json.Unmarshal(data, &d); err != nil {
		return ExplainedDecision{}, fmt.Errorf("decode explain response: %w", err)
	}
	return d, nil
}

// DemoCandidate holds the figures of one model of an explained decision, all of
// them as the gateway returned them.
type DemoCandidate struct {
	Model           string
	P, LCB          float64
	ExpectedCostUSD float64
	BlockN, BlockK  int // the calibration block: BlockK of its BlockN requests succeeded
}

// DemoDecision is the explained decision for one prompt under one profile.
type DemoDecision struct {
	Profile string
	Reason  string
	Lambda  float64
	Chosen  DemoCandidate
}

// DemoServed is what came of the chat request for a prompt.
type DemoServed struct {
	Model      string
	DecisionID string
	CostUSD    *float64 // nil when the response carries no cost
	// Candidate is the figures of the served model in the explanation of the
	// request's profile.
	Candidate DemoCandidate
}

// DemoEntry is what the demo found out about one prompt.
type DemoEntry struct {
	Name      string
	Decisions []DemoDecision // one for each of DemoProfiles, in that order
	Served    DemoServed
}

// DemoResults is what RunDemo found out. Every figure in it is one the gateway
// returned.
type DemoResults struct {
	PolicyVersion string // the policy of every decision
	Entries       []DemoEntry
}

// DemoOptions configures RunDemo.
type DemoOptions struct {
	Client  *Client
	Prompts []DemoPrompt
}

// RunDemo explains every prompt under every profile of DemoProfiles and then
// sends it once as a balanced chat request, one request at a time, prompt by
// prompt. A response that lacks a figure the demo shows is an error: nothing is
// filled in.
func RunDemo(ctx context.Context, o DemoOptions) (DemoResults, error) {
	if o.Client == nil {
		return DemoResults{}, errors.New("demo options need a client")
	}
	if len(o.Prompts) == 0 {
		return DemoResults{}, errors.New("demo options need at least one prompt")
	}
	defer o.Client.Close() // the gateway is stopped next, and waits for idle connections to go

	var res DemoResults
	for _, p := range o.Prompts {
		entry := DemoEntry{Name: p.Name}
		var balanced ExplainedDecision
		for _, profile := range DemoProfiles {
			d, err := o.Client.Explain(ctx, p.Prompt, map[string]string{"X-RouteForge-Profile": profile})
			if err != nil {
				return DemoResults{}, fmt.Errorf("prompt %s, profile %s: %w", p.Name, profile, err)
			}
			dec, err := demoDecision(d, profile)
			if err != nil {
				return DemoResults{}, fmt.Errorf("prompt %s, profile %s: %w", p.Name, profile, err)
			}
			switch {
			case res.PolicyVersion == "":
				res.PolicyVersion = d.PolicyVersion
			case d.PolicyVersion != res.PolicyVersion:
				return DemoResults{}, fmt.Errorf("prompt %s, profile %s: the gateway answered with policy %q after policy %q",
					p.Name, profile, d.PolicyVersion, res.PolicyVersion)
			}
			entry.Decisions = append(entry.Decisions, dec)
			if profile == demoServedProfile {
				balanced = d
			}
		}
		served, err := serveDemoPrompt(ctx, o.Client, p, balanced)
		if err != nil {
			return DemoResults{}, fmt.Errorf("prompt %s: %w", p.Name, err)
		}
		entry.Served = served
		res.Entries = append(res.Entries, entry)
	}
	return res, nil
}

// demoDecision checks an explained decision against the profile it was asked
// for and keeps the figures the demo shows.
func demoDecision(d ExplainedDecision, profile string) (DemoDecision, error) {
	switch {
	case d.Profile != profile:
		return DemoDecision{}, fmt.Errorf("the gateway explained profile %q, not %q", d.Profile, profile)
	case d.PolicyVersion == "":
		return DemoDecision{}, errors.New("the gateway has no policy version, so it runs without a policy")
	case d.Lambda == nil:
		return DemoDecision{}, errors.New("the decision has no lambda")
	}
	chosen, err := demoCandidate(d, d.Chosen)
	if err != nil {
		return DemoDecision{}, err
	}
	return DemoDecision{Profile: d.Profile, Reason: d.Reason, Lambda: *d.Lambda, Chosen: chosen}, nil
}

// demoCandidate returns the figures of model among the candidates of d.
func demoCandidate(d ExplainedDecision, model string) (DemoCandidate, error) {
	i := slices.IndexFunc(d.Candidates, func(c ExplainedCandidate) bool { return c.Model == model })
	if i < 0 {
		return DemoCandidate{}, fmt.Errorf("model %q is not among the candidates", model)
	}
	c := d.Candidates[i]
	var missing []string
	for _, f := range []struct {
		name string
		null bool
	}{
		{"p", c.P == nil}, {"lcb", c.LCB == nil}, {"block_n", c.BlockN == nil},
		{"block_k", c.BlockK == nil}, {"expected_cost_usd", c.ExpectedCostUSD == nil},
	} {
		if f.null {
			missing = append(missing, f.name)
		}
	}
	if len(missing) > 0 {
		return DemoCandidate{}, fmt.Errorf("the candidate %q has no %s", model, strings.Join(missing, ", "))
	}
	return DemoCandidate{
		Model: model, P: *c.P, LCB: *c.LCB, ExpectedCostUSD: *c.ExpectedCostUSD,
		BlockN: *c.BlockN, BlockK: *c.BlockK,
	}, nil
}

// serveDemoPrompt sends p as a balanced chat request, with no strategy header,
// and pairs the model that served it with its figures in the explanation of
// that profile.
func serveDemoPrompt(ctx context.Context, c *Client, p DemoPrompt, explained ExplainedDecision) (DemoServed, error) {
	out, err := c.Chat(ctx, p.Prompt, map[string]string{"X-RouteForge-Profile": demoServedProfile})
	if err != nil {
		return DemoServed{}, fmt.Errorf("chat request: %w", err)
	}
	if out.Status != http.StatusOK {
		return DemoServed{}, fmt.Errorf("chat request: status %d (%s)", out.Status, out.ErrorCode)
	}
	if out.Model == "" || out.DecisionID == "" {
		return DemoServed{}, errors.New("chat response names no model or no decision")
	}
	cand, err := demoCandidate(explained, out.Model)
	if err != nil {
		return DemoServed{}, fmt.Errorf("served model: %w", err)
	}
	return DemoServed{Model: out.Model, DecisionID: out.DecisionID, CostUSD: out.CostUSD, Candidate: cand}, nil
}

// usdFine renders an amount in USD with six decimals, which is what a single
// request needs: it costs a fraction of a cent.
func usdFine(x float64) string { return "$" + fixed(x, 6) }

// RenderDemo renders examples/demo-output.md from the results of RunDemo and
// the trainer's evaluation. Every number in it is formatted from them. The
// evaluation must be of the policy that made the decisions.
func RenderDemo(r DemoResults, ev *Evaluation) (string, error) {
	if ev == nil {
		return "", (ReportInputs{}).require(inEvaluation)
	}
	if len(r.Entries) == 0 {
		return "", errors.New("the demo has no prompts")
	}
	if r.PolicyVersion != ev.PolicyVersion {
		return "", fmt.Errorf("the gateway runs policy %q but %s is of policy %q: run make evaluate",
			r.PolicyVersion, evaluationFileName, ev.PolicyVersion)
	}
	baseline, err := demoBaselineBlocks(ev)
	if err != nil {
		return "", err
	}

	doc := blocks{"# Routing demo", DemoNotice}
	doc.add(fmt.Sprintf("Policy version `%s`. The prompts are in `examples/prompts.json`; this document names them and does not repeat their text.", r.PolicyVersion))
	doc = append(doc, demoDecisionBlocks(r)...)
	doc = append(doc, demoServedBlocks(r)...)
	doc = append(doc, baseline...)
	return doc.String(), nil
}

func demoDecisionBlocks(r DemoResults) []string {
	var rows [][]string
	var chosen []string // the models chosen, in order of first appearance
	decisions := 0
	for _, e := range r.Entries {
		for _, d := range e.Decisions {
			decisions++
			if !slices.Contains(chosen, d.Chosen.Model) {
				chosen = append(chosen, d.Chosen.Model)
			}
			c := d.Chosen
			rows = append(rows, []string{
				e.Name, d.Profile, c.Model, d.Reason, rate(d.Lambda), rate(c.P), rate(c.LCB),
				fmt.Sprintf("%d of %d", c.BlockK, c.BlockN), usdFine(c.ExpectedCostUSD),
			})
		}
	}
	var out blocks
	out.add("## Routing decisions")
	out.add("Each prompt is explained under every profile with `POST /v1/routing/explain`, which routes without calling a provider. " +
		"Lambda is the success probability that a model's 95% lower bound (LCB) must reach under the profile. " +
		"The cheapest model that reaches it is chosen, and when none does the policy's strongest model is. " +
		"p is the calibrated success probability of the chosen model. " +
		"Calibration is the block of the calibration set that the prompt's score falls in: k of its n requests succeeded. " +
		"Expected cost is the policy's estimate for the prompt, from the typical output length of the model.")
	out.add(table([]string{"Prompt", "Profile", "Chosen", "Reason", "Lambda", "p", "LCB", "Calibration (k of n)", "Expected cost"}, rows))
	out.add(fmt.Sprintf("Across these %d decisions the router chose %d different models: %s.", decisions, len(chosen), strings.Join(chosen, ", ")))
	return out
}

func demoServedBlocks(r DemoResults) []string {
	rows := make([][]string, len(r.Entries))
	sentences := make([]string, len(r.Entries))
	for i, e := range r.Entries {
		s := e.Served
		rows[i] = []string{e.Name, s.Model, s.DecisionID, opt(s.CostUSD, usdFine)}
		sentences[i] = fmt.Sprintf("- `%s`: on the calibration set, %d of %d requests scored like this succeeded on %s; 95%% lower bound %s",
			e.Name, s.Candidate.BlockK, s.Candidate.BlockN, s.Model, fixed(s.Candidate.LCB, 2))
	}
	var out blocks
	out.add("## Balanced requests through the gateway")
	out.add("One `routeforge-auto` chat request per prompt, with `X-RouteForge-Profile: balanced` and no strategy header, " +
		"served by the fake providers. Cost is what the gateway recorded for the request. " +
		"The fake providers reply with a short synthetic text, so it is not comparable with the expected cost above.")
	out.add(table([]string{"Prompt", "Served by", "Decision", "Cost"}, rows))
	out.add("## Why each balanced choice")
	out.add("The figures are those of the model that served the request, in the explanation of the balanced profile. " +
		"Where the reason in the decision table is `escalated_no_model_passed`, no model's lower bound reached lambda, " +
		"so the router escalated to the strongest model, and its lower bound is below the bar.")
	out.add(sentences...)
	return out
}

// demoBaselineBlocks is the comparison of the quality router with the
// baselines, from the offline evaluation of the trainer.
func demoBaselineBlocks(ev *Evaluation) ([]string, error) {
	profile := ev.H1.Profile
	quality := "quality/" + ev.ServedPredictor + "/" + profile
	var rows [][]string
	var qualityN int
	for _, key := range []string{"always_strongest", "share_matched_random/" + profile, "static_oracle_family", quality} {
		sum, ok := ev.Strategies[key]
		if !ok {
			return nil, fmt.Errorf("%s has no strategy %q", evaluationFileName, key)
		}
		if key == quality {
			qualityN = sum.N
		}
		rows = append(rows, []string{key, rate(sum.Accuracy), opt(sum.CostPerSuccessUSD, usd), rate(sum.RegretRate)})
	}
	var out blocks
	out.add("## Offline baseline comparison")
	out.add(fmt.Sprintf("From `trainer/artifacts/reports/%s`: policy version `%s`, served predictor `%s`, %s profile, %d test prompts. "+
		"These are offline results of the trainer on its held-out test prompts, not measurements of this run.",
		evaluationFileName, ev.PolicyVersion, ev.ServedPredictor, profile, qualityN))
	out.add(table([]string{"Strategy", "Accuracy", "Cost per success", "Regret rate"}, rows))
	out.add(fmt.Sprintf("The trainer's verdict on hypothesis H1 (%s profile, %s predictor):", ev.H1.Profile, ev.H1.Predictor))
	out.add(h1Verdict(ev.H1))
	return out, nil
}
